def add(left, right):
    """返回两个数的和。"""
    return left + right


def subtract(left, right):
    """返回两个数的差。"""
    return left - right


def multiply(left, right):
    """返回两个数的积。"""
    return left * right


def divide(left, right):
    """返回两个数的商。"""
    return left / right


def power(base, exponent):
    """返回底数的指定次幂。"""
    return base**exponent
